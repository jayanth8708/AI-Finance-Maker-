function getResponse(input) {
  const lower = input.toLowerCase()
  for (const resp of RESPONSES) {
    if (resp.keywords.some((k) => lower.includes(k))) {
      return resp.text
    }
  }
  return "That's a great question! Based on your financial profile, I'd recommend reviewing your monthly spending against your income and identifying areas where you can optimize. Would you like me to analyze your budgets, investments, or tax planning strategies in more detail?"
}

function MessageBubble({ message }) {
  const isUser = message.role === 'user'

  const renderText = (text) => {
    return text.split('\n').map((line, i) => {
      const bold = line.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
      return <p key={i} className={line.startsWith('*') ? 'text-xs text-gray-400 italic' : ''} dangerouslySetInnerHTML={{ __html: bold }} />
    })
  }

  return (
    <div className={`flex ${isUser ? 'justify-end' : 'justify-start'} mb-4`}>
      {!isUser && (
        <div className="w-8 h-8 rounded-full bg-primary-600 flex items-center justify-center flex-shrink-0 mr-2.5 mt-0.5">
          <span className="text-xs font-bold text-white">AI</span>
        </div>
      )}
      <div
        className={`max-w-[75%] rounded-2xl px-4 py-3 text-sm leading-relaxed space-y-1 ${
          isUser
            ? 'bg-primary-600 text-white rounded-tr-sm'
            : 'bg-white border border-gray-100 text-gray-700 shadow-card rounded-tl-sm'
        }`}
      >
        {renderText(message.text)}
        <p className={`text-xs mt-1 ${isUser ? 'text-primary-200' : 'text-gray-400'}`}>
          {new Date(message.timestamp).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' })}
        </p>
      </div>
    </div>
  )
}

export default function AdvisorPage() {
  const { user } = useAuth()
  const [messages, setMessages] = useState(INITIAL_MESSAGES)
  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(false)
  const endRef = useRef(null)

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [messages])

  const handleSend = () => {
    const text = input.trim()
    if (!text) return

    const userMessage = { id: Date.now(), role: 'user', text, timestamp: new Date().toISOString() }
    setMessages((m) => [...m, userMessage])
    setInput('')
    setLoading(true)

    setTimeout(() => {
      const response = getResponse(text)
      const aiMessage = { id: Date.now() + 1, role: 'assistant', text: response, timestamp: new Date().toISOString() }
      setMessages((m) => [...m, aiMessage])
      setLoading(false)
    }, 1000 + Math.random() * 500)
  }

  const handleKeyDown = (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault()
      handleSend()
    }
  }

  const QUICK_PROMPTS = [
    'How should I budget my salary?',
    'Best way to start investing?',
    'Help me build an emergency fund',
    'How to save on taxes?',
  ]

  return (
    <div className="max-w-3xl mx-auto flex flex-col h-[calc(100vh-7rem)]">
      {/* Header */}
      <div className="mb-4">
        <h1 className="text-2xl font-bold text-gray-900">AI Financial Advisor</h1>
        <p className="text-gray-500 text-sm">
          Simulated AI advisor — responses are pre-defined for demonstration
        </p>
      </div>

      {/* Chat */}
      <div className="card flex-1 flex flex-col overflow-hidden">
        <div className="flex-1 overflow-y-auto p-5 no-scrollbar">
          {messages.map((m) => (
            <MessageBubble key={m.id} message={m} />
          ))}
          {loading && (
            <div className="flex items-center gap-2 mb-4">
              <div className="w-8 h-8 rounded-full bg-primary-600 flex items-center justify-center flex-shrink-0">
                <span className="text-xs font-bold text-white">AI</span>
              </div>
              <div className="bg-white border border-gray-100 shadow-card rounded-2xl rounded-tl-sm px-4 py-3">
                <div className="flex gap-1 items-center h-4">
                  <div className="w-1.5 h-1.5 bg-gray-400 rounded-full animate-bounce" style={{ animationDelay: '0ms' }} />
                  <div className="w-1.5 h-1.5 bg-gray-400 rounded-full animate-bounce" style={{ animationDelay: '150ms' }} />
                  <div className="w-1.5 h-1.5 bg-gray-400 rounded-full animate-bounce" style={{ animationDelay: '300ms' }} />
                </div>
              </div>
            </div>
          )}
          <div ref={endRef} />
        </div>

        {/* Quick prompts */}
        {messages.length <= 1 && (
          <div className="px-5 pb-3 flex flex-wrap gap-2">
            {QUICK_PROMPTS.map((prompt) => (
              <button
                key={prompt}
                onClick={() => { setInput(prompt); }}
                className="text-xs px-3 py-1.5 rounded-full border border-primary-200 text-primary-700 hover:bg-primary-50 transition-colors"
              >
                {prompt}
              </button>
            ))}
          </div>
        )}

        {/* Input */}
        <div className="border-t border-gray-100 p-4 flex gap-3">
          <textarea
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={handleKeyDown}
            rows={1}
            className="input flex-1 resize-none py-2.5 leading-normal"
            placeholder="Ask about budgeting, investments, savings..."
            style={{ minHeight: '42px', maxHeight: '120px' }}
          />
          <button
            onClick={handleSend}
            disabled={!input.trim() || loading}
            className="btn-primary p-2.5 aspect-square flex-shrink-0"
          >
            <Send size={16} />
          </button>
        </div>
      </div>
    </div>
  )
}
